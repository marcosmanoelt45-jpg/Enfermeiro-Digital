// Converte string separada por vírgula em array (sem espaços vazios).
export function parseList(value) {
  if (!value) return [];
  return String(value)
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
}

// Converte array em string separada por vírgula.
export function joinList(arr) {
  return (arr || []).filter(Boolean).join(", ");
}
